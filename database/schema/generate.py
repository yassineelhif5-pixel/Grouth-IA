HEADER = "-- GENERATED by database/schema/generate.py — DO NOT EDIT BY HAND\n"


def q(v: str, c: Column) -> str:
    if c.dsl_type in ("int", "bigint", "num"):
        return v
    return "'" + v.replace("'", "''") + "'"


def tenant_not_null(t: Table) -> bool:
    c = t.col("tenant_id")
    return bool(c and c.not_null)


def short(name: str, limit: int = 63) -> str:
    if len(name) <= limit:
        return name
    import hashlib
    h = hashlib.md5(name.encode()).hexdigest()[:6]
    return name[: limit - 7] + "_" + h


# ───────────────────────────── SQL: tables ─────────────────────────────
def sql_tables() -> str:
    out = [HEADER, "-- Migration 0002 — tables, constraints, indexes, comments\n"]
    fks, idx, comments, vec = [], [], [], []
    for t in REGISTRY:
        lines = []
        if t.pk_ref:
            lines.append("  id uuid PRIMARY KEY")
            fks.append(f"ALTER TABLE public.{t.name} ADD CONSTRAINT {short(t.name + '_id_fkey')} "
                       f"FOREIGN KEY (id) REFERENCES auth.users(id) ON DELETE CASCADE;")
        elif t.partition:
            lines.append("  id uuid NOT NULL DEFAULT gen_random_uuid()")
        else:
            lines.append("  id uuid PRIMARY KEY DEFAULT gen_random_uuid()")
        for c in t.columns:
            if c.dsl_type == "vec":
                vec.append((t, c))
                continue
            s = f"  {c.name} {c.sqltype}"
            if c.not_null:
                s += " NOT NULL"
            if c.default is not None:
                s += f" DEFAULT {c.default}"
            if c.check_in:
                vals = ", ".join(q(v, c) for v in c.check_in)
                s += f" CHECK ({c.name} IN ({vals}))"
            lines.append(s)
        if t.partition:
            lines.append("  PRIMARY KEY (id, created_at)")
        elif tenant_not_null(t):
            lines.append(f"  CONSTRAINT {short(t.name + '_tenant_id_id_key')} UNIQUE (tenant_id, id)")
        body = ",\n".join(lines)
        part = " PARTITION BY RANGE (created_at)" if t.partition else ""
        out.append(f"CREATE TABLE IF NOT EXISTS public.{t.name} (\n{body}\n){part};")
        if t.partition:
            out.append(f"CREATE TABLE IF NOT EXISTS public.{t.name}_default PARTITION OF public.{t.name} DEFAULT;")
        # additive evolution: every column is (re)declared idempotently so new columns reach existing databases
        adds = []
        for c in t.columns:
            if c.dsl_type == "vec":
                continue
            a = f"ADD COLUMN IF NOT EXISTS {c.name} {c.sqltype}"
            if c.default is not None:
                a += f" DEFAULT {c.default}"
            if c.not_null and c.default is not None:
                a += " NOT NULL"
            if c.check_in and not c.recheck:
                a += f" CHECK ({c.name} IN ({', '.join(q(v, c) for v in c.check_in)}))"
            adds.append(a)
        out.append(f"ALTER TABLE public.{t.name} " + ",\n  ".join(adds) + ";")
        for c in t.columns:
            if c.recheck:
                cn = short(f"{t.name}_{c.name}_check")
                out.append(f"ALTER TABLE public.{t.name} DROP CONSTRAINT IF EXISTS {cn}, ADD CONSTRAINT {cn} "
                           f"CHECK ({c.name} IN ({', '.join(q(v, c) for v in c.check_in)}));")
            if c.relax_not_null:
                out.append(f"ALTER TABLE public.{t.name} ALTER COLUMN {c.name} DROP NOT NULL;")
            if getattr(c, "reset_default", False):
                out.append(f"ALTER TABLE public.{t.name} ALTER COLUMN {c.name} SET DEFAULT {c.default};")
        out.append("")

        # uniques
        uniq_sets: list[tuple[str, ...]] = []
        for c in t.columns:
            if c.unique:
                uniq_sets.append(("tenant_id", c.name) if t.tenant and c.name != "tenant_id" else (c.name,))
        uniq_sets += t.uniques
        for u in uniq_sets:
            cols = list(u)
            if t.partition and "created_at" not in cols:
                cols.append("created_at")
            name = short(f"{t.name}_{'_'.join(u)}_key")
            nnd = " NULLS NOT DISTINCT" if ("tenant_id" in cols and not tenant_not_null(t)) else ""
            if t.soft_delete:
                idx.append(f"CREATE UNIQUE INDEX IF NOT EXISTS {name} ON public.{t.name} ({', '.join(cols)}){nnd} WHERE deleted_at IS NULL;")
            else:
                idx.append(f"CREATE UNIQUE INDEX IF NOT EXISTS {name} ON public.{t.name} ({', '.join(cols)}){nnd};")

        # foreign keys + FK indexes
        for c in t.columns:
            if not c.fk:
                continue
            od = {"restrict": "RESTRICT", "cascade": "CASCADE", "setnull": "SET NULL"}[c.on_delete]
            cname = short(f"{t.name}_{c.name}_fkey")
            if c.fk == "auth.users":
                fks.append(f"ALTER TABLE public.{t.name} ADD CONSTRAINT {cname} FOREIGN KEY ({c.name}) "
                           f"REFERENCES auth.users(id) ON DELETE {od};")
                if c.name not in ("created_by", "updated_by"):
                    idx.append(f"CREATE INDEX IF NOT EXISTS {short(f'ix_{t.name}_{c.name}')} ON public.{t.name} ({c.name});")
                continue
            target = T[c.fk]
            composite = (c.name != "tenant_id" and tenant_not_null(t) and tenant_not_null(target)
                         and not target.partition)
            if composite:
                if od == "SET NULL":
                    od = f"SET NULL ({c.name})"
                fks.append(f"ALTER TABLE public.{t.name} ADD CONSTRAINT {cname} FOREIGN KEY (tenant_id, {c.name}) "
                           f"REFERENCES public.{target.name}(tenant_id, id) ON DELETE {od};")
                idx.append(f"CREATE INDEX IF NOT EXISTS {short(f'ix_{t.name}_{c.name}')} ON public.{t.name} (tenant_id, {c.name});")
            else:
                fks.append(f"ALTER TABLE public.{t.name} ADD CONSTRAINT {cname} FOREIGN KEY ({c.name}) "
                           f"REFERENCES public.{target.name}(id) ON DELETE {od};")
                if c.name != "tenant_id":
                    idx.append(f"CREATE INDEX IF NOT EXISTS {short(f'ix_{t.name}_{c.name}')} ON public.{t.name} ({c.name});")

        # standard indexes
        names = {c.name for c in t.columns}
        if t.tenant:
            idx.append(f"CREATE INDEX IF NOT EXISTS {short(f'ix_{t.name}_tenant_created')} ON public.{t.name} (tenant_id, created_at DESC);")
        elif "created_at" in names and t.append_only:
            idx.append(f"CREATE INDEX IF NOT EXISTS {short(f'ix_{t.name}_created')} ON public.{t.name} (created_at DESC);")
        if "correlation_id" in names:
            idx.append(f"CREATE INDEX IF NOT EXISTS {short(f'ix_{t.name}_correlation')} ON public.{t.name} (correlation_id) WHERE correlation_id IS NOT NULL;")
        if "status" in names:
            cols = "tenant_id, status" if t.tenant else "status"
            idx.append(f"CREATE INDEX IF NOT EXISTS {short(f'ix_{t.name}_status')} ON public.{t.name} ({cols});")
        if "execution_id" in names and ("execution_id",) not in t.indexes:
            idx.append(f"CREATE INDEX IF NOT EXISTS {short(f'ix_{t.name}_execution')} ON public.{t.name} (execution_id) WHERE execution_id IS NOT NULL;")
        for i in t.indexes:
            idx.append(f"CREATE INDEX IF NOT EXISTS {short(f'ix_{t.name}_' + '_'.join(i))} ON public.{t.name} ({', '.join(i)});")

        comments.append(f"COMMENT ON TABLE public.{t.name} IS {q(f'[{t.domain}] ' + (t.comment or t.name), Column('', '', 'text'))};")
        for c in t.columns:
            if c.comment and c.dsl_type != "vec":
                comments.append(f"COMMENT ON COLUMN public.{t.name}.{c.name} IS {q(c.comment, Column('', '', 'text'))};")

    out.append("-- ── Foreign keys (added after all tables exist: cycle-safe) ──")
    out += [f"DO $$ BEGIN {f} EXCEPTION WHEN duplicate_object THEN NULL; END $$;" for f in fks]
    out.append("\n-- ── Indexes ──")
    out += sorted(set(idx), key=idx.index)
    out.append("\n-- ── pgvector columns (only when the extension is available) ──")
    for t, c in vec:
        out.append(
            "DO $$ BEGIN IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'vector') THEN "
            f"ALTER TABLE public.{t.name} ADD COLUMN IF NOT EXISTS {c.name} extensions.vector(1536); "
            f"CREATE INDEX IF NOT EXISTS ix_{t.name}_{c.name}_hnsw ON public.{t.name} USING hnsw ({c.name} extensions.vector_cosine_ops); "
            "END IF; END $$;")
    out.append("\n-- ── Comments ──")
    out += comments
    return "\n".join(out) + "\n"


# ───────────────────────────── SQL: triggers ─────────────────────────────
def sql_triggers() -> str:
    out = [HEADER, "-- Migration 0004 — traceability triggers attached to every table\n"]
    for t in REGISTRY:
        names = {c.name for c in t.columns}
        n = t.name
        out.append(f"DROP TRIGGER IF EXISTS trg_00_context ON public.{n};")
        out.append(f"CREATE TRIGGER trg_00_context BEFORE INSERT ON public.{n} FOR EACH ROW EXECUTE FUNCTION app.tg_fill_context({"'versioned'" if t.versioned else ""});")
        if t.append_only:
            out.append(f"DROP TRIGGER IF EXISTS trg_01_append_only ON public.{n};")
            out.append(f"CREATE TRIGGER trg_01_append_only BEFORE UPDATE OR DELETE ON public.{n} FOR EACH ROW EXECUTE FUNCTION app.tg_append_only();")
        elif t.no_delete:
            out.append(f"DROP TRIGGER IF EXISTS trg_01_append_only ON public.{n};")
            out.append(f"DROP TRIGGER IF EXISTS trg_01_no_delete ON public.{n};")
            out.append(f"CREATE TRIGGER trg_01_no_delete BEFORE DELETE ON public.{n} FOR EACH ROW EXECUTE FUNCTION app.tg_append_only();")
            out.append(f"DROP TRIGGER IF EXISTS trg_01_touch ON public.{n};")
            out.append(f"CREATE TRIGGER trg_01_touch BEFORE UPDATE ON public.{n} FOR EACH ROW EXECUTE FUNCTION app.tg_touch();")
        elif "updated_at" in names:
            out.append(f"DROP TRIGGER IF EXISTS trg_01_touch ON public.{n};")
            out.append(f"CREATE TRIGGER trg_01_touch BEFORE UPDATE ON public.{n} FOR EACH ROW EXECUTE FUNCTION app.tg_touch();")
        if t.versioned:
            secrets = [c.name for c in t.columns if c.secret]
            args = ", ".join(q(s, Column('', '', 'text')) for s in secrets)
            out.append(f"DROP TRIGGER IF EXISTS trg_90_history ON public.{n};")
            out.append(f"CREATE TRIGGER trg_90_history AFTER INSERT OR UPDATE OR DELETE ON public.{n} "
                       f"FOR EACH ROW EXECUTE FUNCTION app.tg_entity_history({args});")
    return "\n".join(out) + "\n"


# ───────────────────────────── SQL: RLS ─────────────────────────────
def read_expr(t: Table) -> str | None:
    r = t.read
    if r == "none":
        return None
    user_col = "id" if t.pk_ref else "user_id"
    base = {
        "member": "app.is_tenant_member(tenant_id)",
        "member_or_shared": "(tenant_id IS NULL OR app.is_tenant_member(tenant_id))",
        "admin": "app.is_tenant_admin(tenant_id)",
        "self": f"{user_col} = (SELECT auth.uid())",
        "global": "true",
        "tenant_row": "app.is_tenant_member(id)",
        "pilot": "false",
    }[r]
    if t.app not in PRIVATE_APPS and r != "global":
        base = f"({base}) OR app.is_platform_admin()"
    return base


def sql_rls() -> str:
    out = [HEADER, "-- Migration 0005 — Row Level Security, grants and policies\n"]
    for t in REGISTRY:
        n = t.name
        out.append(f"-- {n} [{t.kind}/{t.read}]")
        out.append(f"ALTER TABLE public.{n} ENABLE ROW LEVEL SECURITY;")
        out.append(f"REVOKE ALL ON public.{n} FROM anon;")
        out.append(f"REVOKE INSERT, UPDATE, DELETE, TRUNCATE ON public.{n} FROM authenticated;")
        out.append(f"GRANT SELECT ON public.{n} TO authenticated;")
        if t.partition:
            out.append(f"ALTER TABLE public.{n}_default ENABLE ROW LEVEL SECURITY;")
            out.append(f"REVOKE ALL ON public.{n}_default FROM anon, authenticated;")
        if t.append_only:
            out.append(f"GRANT SELECT, INSERT ON public.{n} TO app_backend;")
            out.append(f"REVOKE UPDATE, DELETE, TRUNCATE ON public.{n} FROM app_backend;")
        elif t.no_delete:
            out.append(f"GRANT SELECT, INSERT, UPDATE ON public.{n} TO app_backend;")
            out.append(f"REVOKE DELETE, TRUNCATE ON public.{n} FROM app_backend;")
        else:
            out.append(f"GRANT SELECT, INSERT, UPDATE, DELETE ON public.{n} TO app_backend;")
        for pol in ("p_auth_read", "p_backend_read", "p_backend_write"):
            out.append(f"DROP POLICY IF EXISTS {pol} ON public.{n};")
        e = read_expr(t)
        if e:
            out.append(f"CREATE POLICY p_auth_read ON public.{n} FOR SELECT TO authenticated USING ({e});")
        # backend (Django / Celery) — tenant context enforced at DB level too
        if n == "tenants":
            rd = "id = app.current_tenant_id() OR app.current_is_platform() OR app.backend_user_is_member(id)"
            wr = "id = app.current_tenant_id() OR app.current_is_platform()"
        elif tenant_not_null(t):
            rd = "tenant_id = app.current_tenant_id() OR app.current_is_platform() OR app.backend_user_is_member(tenant_id)"
            wr = "tenant_id = app.current_tenant_id() OR app.current_is_platform()"
        elif t.tenant:
            rd = "tenant_id IS NULL OR tenant_id = app.current_tenant_id() OR app.current_is_platform() OR app.backend_user_is_member(tenant_id)"
            wr = "tenant_id IS NULL OR tenant_id = app.current_tenant_id() OR app.current_is_platform()"
        else:
            rd = wr = "true"
        out.append(f"CREATE POLICY p_backend_read ON public.{n} FOR SELECT TO app_backend USING ({rd});")
        if t.append_only:
            out.append(f"CREATE POLICY p_backend_write ON public.{n} FOR INSERT TO app_backend WITH CHECK ({wr});")
        else:
            out.append(f"CREATE POLICY p_backend_write ON public.{n} FOR ALL TO app_backend USING ({wr}) WITH CHECK ({wr});")
        out.append("")
    return "\n".join(out) + "\n"


# ───────────────────────────── Django models ─────────────────────────────
def model_name(table: str) -> str:
    base = table
    if base.endswith("ies"):
        base = base[:-3] + "y"
    elif base.endswith("s") and not base.endswith("ss"):
        base = base[:-1]
    return "".join(p.capitalize() for p in base.split("_"))


DJ = {"uuid": "models.UUIDField", "text": "models.TextField", "int": "models.IntegerField",
      "bigint": "models.BigIntegerField", "bool": "models.BooleanField", "ts": "models.DateTimeField",
      "date": "models.DateField", "json": "models.JSONField", "inet": "models.GenericIPAddressField"}


RESERVED_ATTRS = {"check", "save", "delete", "clean", "objects", "pk", "full_clean", "refresh_from_db", "serializable_value",
                  "validate_unique", "validate_constraints", "get_deferred_fields", "from_db", "prepare_database_save"}


def dj_field(t: Table, c: Column) -> str | None:
    if c.dsl_type == "vec":
        return None
    kw = []
    if not c.not_null:
        kw += ["null=True", "blank=True"]
    if c.default is not None:
        d = c.default
        if d == "now()":
            kw.append("default=_tz.now")
        elif d in ("true", "false"):
            kw.append(f"default={d == 'true'}")
        elif d.startswith("'"):
            v = d.strip("'")
            if c.dsl_type == "json":
                kw.append("default=dict" if v == "{}" else "default=list")
            else:
                kw.append(f"default={v!r}")
        else:
            kw.append(f"default={d}")
    if c.check_in:
        kw.append("choices=[" + ", ".join(f"({v!r}, {v!r})" if c.dsl_type == "text" else f"({v}, {v!r})" for v in c.check_in) + "]")
    if c.comment:
        kw.append(f"help_text={c.comment!r}")
    if c.fk and c.fk != "auth.users":
        target = T[c.fk]
        ref = f"'{target.app}.{model_name(target.name)}'" if target.name != t.name else "'self'"
        fname = c.name[:-3] if c.name.endswith("_id") else c.name + "_ref"
        if fname in RESERVED_ATTRS:
            fname += "_ref"
        kw = [k for k in kw if not k.startswith("default")]
        return (f"    {fname} = models.ForeignKey({ref}, on_delete=models.DO_NOTHING, db_column={c.name!r}, "
                f"related_name='+', {', '.join(kw + ['db_constraint=False'])})")
    if c.dsl_type == "num":
        if "(" in c.sqltype:
            p, s = c.sqltype[c.sqltype.index("(") + 1:-1].split(",")
            kw = [f"max_digits={p}", f"decimal_places={s}"] + kw
        else:
            kw = ["max_digits=24", "decimal_places=6"] + kw
        typ = "models.DecimalField"
    elif c.dsl_type in ("text[]", "uuid[]"):
        inner = "models.TextField()" if c.dsl_type == "text[]" else "models.UUIDField()"
        return f"    {c.name} = ArrayField({inner}, {', '.join(kw)})"
    else:
        typ = DJ[c.dsl_type]
    return f"    {c.name} = {typ}({', '.join(kw)})"


def django_models() -> dict[str, str]:
    by_app: dict[str, list[Table]] = defaultdict(list)
    for t in REGISTRY:
        by_app[t.app].append(t)
    files = {}
    for app, tables in by_app.items():
        lines = [HEADER.replace("--", "#"), '"""Unmanaged models mapping the SQL schema (source: database/schema)."""',
                 "import uuid as _uuid", "", "from django.contrib.postgres.fields import ArrayField  # noqa: F401",
                 "from django.db import models", "from django.utils import timezone as _tz  # noqa: F401", ""]
        for t in tables:
            lines.append("")
            lines.append(f"class {model_name(t.name)}(models.Model):")
            lines.append(f'    """{(t.comment or t.name)} [{t.kind}]"""')
            lines.append("")
            lines.append("    id = models.UUIDField(primary_key=True, default=_uuid.uuid4, editable=False)")
            for c in t.columns:
                f = dj_field(t, c)
                if f:
                    lines.append(f)
            lines.append("")
            lines.append("    class Meta:")
            lines.append("        managed = False")
            lines.append(f"        db_table = {t.name!r}")
            lines.append("")
            secrets = [c.name for c in t.columns if c.secret]
            lines.append(f"    TRACE_KIND = {t.kind!r}")
            lines.append(f"    SECRET_FIELDS = {tuple(secrets)!r}")
            lines.append("")
        files[app] = "\n".join(lines).rstrip() + "\n"
    return files


# ───────────────────────────── Docs ─────────────────────────────
def docs() -> dict[str, str]:
    by_dom: dict[str, list[Table]] = defaultdict(list)
    for t in REGISTRY:
        by_dom[t.domain].append(t)
    n_fk = sum(1 for t in REGISTRY for c in t.columns if c.fk) + sum(1 for t in REGISTRY if t.pk_ref)
    ov = ["# Schema overview", "", HEADER.replace("-- ", "> "),
          f"- Tables: **{len(REGISTRY)}** (+ partitions)",
          f"- Foreign keys: **{n_fk}**",
          f"- Tenant-isolated tables: **{sum(1 for t in REGISTRY if t.tenant)}**",
          f"- Versioned tables (entity_history): **{sum(1 for t in REGISTRY if t.versioned)}**",
          f"- Append-only tables: **{sum(1 for t in REGISTRY if t.append_only)}**",
          f"- Partitioned tables: **{sum(1 for t in REGISTRY if t.partition)}**", "",
          "| Domain | Tables | Django app(s) |", "|---|---|---|"]
    for d, ts in by_dom.items():
        ov.append(f"| {d} | {len(ts)} | {', '.join(sorted({t.app for t in ts}))} |")
    ov += ["", "## Table kinds", "", "| Kind | Meaning |", "|---|---|",
           "| biz / conf | tenant data, soft-delete, versioned in `entity_history` |",
           "| log | tenant append-only events (UPDATE/DELETE blocked) |",
           "| ref | global reference data |", "| gbiz | global versioned data |",
           "| glog | global append-only log (tenant_id nullable) |",
           "| run | tenant execution record: status transitions allowed, DELETE forbidden |"]
    dd = ["# Data dictionary", "", HEADER.replace("-- ", "> "),
          "Generic columns: `id` uuid PK; `tenant_id` isolation key; `created_at/updated_at` timestamptz UTC; "
          "`created_by/updated_by` → auth.users; `deleted_at` soft delete; `version_number` optimistic version "
          "(incremented by trigger, mirrored in entity_history); `correlation_id` end-to-end trace id.", ""]
    for d, ts in by_dom.items():
        dd.append(f"## {d}")
        for t in ts:
            dd += ["", f"### `{t.name}`", "", f"{t.comment or ''} — kind `{t.kind}`, RLS read `{t.read}`, app `{t.app}`"
                   + (", partitioned by month" if t.partition else ""), "",
                   "| Column | Type | Null | Default | Constraint | Notes |", "|---|---|---|---|---|---|"]
            for c in t.columns:
                cons = []
                if c.fk:
                    cons.append(f"→ {c.fk} ({c.on_delete})")
                if c.unique:
                    cons.append("unique")
                if c.check_in:
                    cons.append("in(" + ", ".join(c.check_in) + ")")
                if c.secret:
                    cons.append("**secret**")
                dd.append(f"| {c.name} | {c.sqltype} | {'' if c.not_null else 'yes'} | {c.default or ''} | "
                          f"{' '.join(cons)} | {c.comment} |")
            for u in t.uniques:
                dd.append(f"\nUnique: `({', '.join(u)})`")
        dd.append("")
    erd = ["# ERD", "", HEADER.replace("-- ", "> "),
           "One Mermaid diagram per domain (relations to `tenants` and `auth.users` omitted for readability).", ""]
    for d, ts in by_dom.items():
        erd += [f"## {d}", "", "```mermaid", "erDiagram"]
        names = {t.name for t in ts}
        rels = set()
        for t in ts:
            for c in t.columns:
                if c.fk and c.fk not in ("tenants", "auth.users"):
                    card = "||--o{" if not c.unique else "||--||"
                    rels.add(f"    {c.fk} {card} {t.name} : {c.name}")
            if not any(c.fk and c.fk not in ("tenants", "auth.users") for c in t.columns):
                erd.append(f"    {t.name} {{ uuid id }}")
        erd += sorted(rels)
        erd += ["```", ""]
        _ = names
    return {"SCHEMA_OVERVIEW.md": "\n".join(ov) + "\n", "DATA_DICTIONARY.md": "\n".join(dd) + "\n",
            "ERD.md": "\n".join(erd) + "\n"}


def main() -> None:
    mig = ROOT / "database" / "migrations"
    mig.mkdir(parents=True, exist_ok=True)
    (mig / "0002_tables.sql").write_text(sql_tables())
    (mig / "0004_triggers.sql").write_text(sql_triggers())
    (mig / "0005_rls.sql").write_text(sql_rls())
    for app, src in django_models().items():
        p = ROOT / "backend" / "apps" / app
        p.mkdir(parents=True, exist_ok=True)
        (p / "models.py").write_text(src)
    dd = ROOT / "docs" / "database"
    dd.mkdir(parents=True, exist_ok=True)
    for name, txt in docs().items():
        (dd / name).write_text(txt)
    # full snapshot
    parts = sorted(mig.glob("*.sql"))
    (ROOT / "database" / "schema.sql").write_text(
        "-- Growth IA — full schema snapshot (concatenation of database/migrations, in order)\n\n"
        + "\n".join(f"-- >>> {p.name}\n" + p.read_text() for p in parts))
    print(f"tables={len(REGISTRY)} apps={len(django_models())}")


if __name__ == "__main__":
    main()
